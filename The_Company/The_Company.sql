SELECT Com.COMPANY_CODE, Com.FOUNDER, 
COUNT(DISTINCT Emp.LEAD_MANAGER_CODE), 
COUNT(DISTINCT Emp.SENIOR_MANAGER_CODE), 
COUNT(DISTINCT Emp.MANAGER_CODE), 
COUNT(DISTINCT Emp.EMPLOYEE_CODE)

FROM COMPANY Com LEFT JOIN EMPLOYEE Emp
ON Com.COMPANY_CODE = Emp.COMPANY_CODE

GROUP BY Com.COMPANY_CODE, Com.FOUNDER
ORDER BY Com.COMPANY_CODE ASC;